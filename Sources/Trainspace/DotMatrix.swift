/// A 5×8 dot-matrix typeface, drawn dot by dot like the LED signs on station platforms.
/// Each glyph is eight rows of five bits (bit 4 = leftmost column); rows 0–6 hold capitals,
/// row 7 is for descenders.
enum DotMatrix {
    static let columns = 5
    static let rows = 8

    /// Column advance per character, including one blank column of spacing.
    static let advance = 6

    static func glyph(_ c: Character) -> [UInt8] {
        glyphs[c] ?? glyphs[Character(c.uppercased())] ?? glyphs["?"]!
    }

    /// Lit dots for `text`, laid out from `origin` (top-left), `pitch` points apart.
    static func path(_ text: String, origin: CGPoint, pitch: CGFloat, dot: CGFloat) -> Path {
        var path = Path()
        var x = origin.x
        for c in text {
            let g = glyph(c)
            for (row, bits) in g.enumerated() where bits != 0 {
                for col in 0..<columns where bits & (0x10 >> UInt8(col)) != 0 {
                    let cx = x + CGFloat(col) * pitch, cy = origin.y + CGFloat(row) * pitch
                    path.addEllipse(in: CGRect(x: cx - dot / 2, y: cy - dot / 2, width: dot, height: dot))
                }
            }
            x += CGFloat(advance) * pitch
        }
        return path
    }

    /// Every dot position of a panel, lit or not, for the faint unlit grid.
    static func gridPath(columns: Int, rows: Int, origin: CGPoint, pitch: CGFloat, dot: CGFloat) -> Path {
        var path = Path()
        guard columns > 0, rows > 0 else { return path }
        for r in 0..<rows {
            for c in 0..<columns {
                path.addEllipse(in: CGRect(x: origin.x + CGFloat(c) * pitch - dot / 2, y: origin.y + CGFloat(r) * pitch - dot / 2,
                                           width: dot, height: dot))
            }
        }
        return path
    }

