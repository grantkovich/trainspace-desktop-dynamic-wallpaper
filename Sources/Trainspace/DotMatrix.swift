/// One LED sign: rows of fixed-width text fields on a black panel with a faint unlit grid.
struct LEDSign: View {
    struct Field {
        var text: String
        /// Width in characters; text is cut to fit.
        var width: Int
        var alignRight = false
        var color: RGBA?
        /// A solid route mark lit behind the field: NYCT's bullets, SEPTA Metro's route codes.
        var badge: Badge?

        struct Badge { var color: RGBA; var round: Bool }
    }

    let rows: [[Field]]
    let color: RGBA
    var pitch: CGFloat = 2.6
    /// Blank dot rows between text rows.
    var rowGap = 3
    /// The panel's width in characters, when no row fills it (a sign with nothing to show yet).
    var minColumns = 1

    static func size(columns: Int, rows: Int, pitch: CGFloat, rowGap: Int = 3, padding: CGFloat = 14) -> CGSize {
        let dotCols = columns * DotMatrix.advance - 1
        let dotRows = rows * DotMatrix.rows + max(0, rows - 1) * rowGap
        return CGSize(width: CGFloat(dotCols - 1) * pitch + padding * 2, height: CGFloat(dotRows - 1) * pitch + padding * 2)
    }

    var columns: Int { max(minColumns, rows.map { $0.reduce(0) { $0 + $1.width } }.max() ?? 0) }

    var body: some View {
        let size = Self.size(columns: columns, rows: rows.count, pitch: pitch, rowGap: rowGap)
        Canvas { ctx, size in
            let padding: CGFloat = 14
            let dot = pitch * 0.72
            ctx.fill(Path(roundedRect: CGRect(origin: .zero, size: size), cornerRadius: 6), with: .color(RGBA(hex: 0x050505).color))
            let dotCols = columns * DotMatrix.advance - 1
            let dotRows = rows.count * DotMatrix.rows + max(0, rows.count - 1) * rowGap
            ctx.fill(DotMatrix.gridPath(columns: dotCols, rows: dotRows, origin: CGPoint(x: padding, y: padding), pitch: pitch, dot: dot),
                     with: .color(color.with(alpha: 0.07).color))
            var lit: [RGBA: Path] = [:]
            for (r, fields) in rows.enumerated() {
                var col = 0
                let y = padding + CGFloat(r * (DotMatrix.rows + rowGap)) * pitch
                for f in fields {
                    if let b = f.badge {
                        // Centred on the field, a little taller than a capital.
                        let x0 = padding + CGFloat(col * DotMatrix.advance) * pitch
                        let w = CGFloat(f.width * DotMatrix.advance - 1) * pitch, h = CGFloat(DotMatrix.rows + 1) * pitch
                        let side = b.round ? min(w, h) : w
                        let r = CGRect(x: x0 + (w - side) / 2 - pitch * 0.5, y: y - pitch * 1.2, width: side, height: h)
                        let shape = b.round ? Path(ellipseIn: r) : Path(roundedRect: r, cornerRadius: pitch * 1.5)
                        ctx.fill(shape, with: .color(b.color.color))
                    }
                    var text = String(f.text.prefix(f.width))
                    if f.alignRight { text = String(repeating: " ", count: f.width - text.count) + text }
                    var x = padding + CGFloat(col * DotMatrix.advance) * pitch
                    // Letters on a badge sit in its middle.
                    if f.badge != nil { x += CGFloat((f.width - text.count) * DotMatrix.advance) * pitch / 2 }
                    lit[f.color ?? color, default: Path()].addPath(DotMatrix.path(text, origin: CGPoint(x: x, y: y), pitch: pitch, dot: dot))
                    col += f.width
                }
            }
            for (c, path) in lit {
                // A soft bloom under the lit dots, then the dots.
                var glow = ctx
                glow.addFilter(.blur(radius: pitch * 0.9))
                glow.fill(path, with: .color(c.with(alpha: 0.55).color))
                ctx.fill(path, with: .color(c.color))
            }
        }
        .frame(width: size.width, height: size.height)
    }
}
